// =========================================================
// NORMALISATION
// =========================================================

function normalize(str) {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}


// =========================================================
// RECHERCHE DE LA MEILLEURE RÉPONSE
// =========================================================

export function findAnswer(userInput) {
  const normalizedInput = normalize(userInput)
  const words = normalizedInput
    .split(/\W+/)
    .filter((w) => w.length > 2)

  let best = null
  let bestScore = 0
  let tie = false

  for (const item of faq) {
    let score = 0

    for (const keyword of item.keywords) {
      const nk = normalize(keyword)

      if (normalizedInput.includes(nk)) {
        score += 3 + Math.min(nk.split(' ').length - 1, 2)
      } else if (words.some((w) => w === nk)) {
        score += 1.5
      } else if (
        words.some((w) => nk.includes(w) && w.length > 3)
      ) {
        score += 0.5
      }
    }

    if (score > bestScore) {
      bestScore = score
      best = item
      tie = false
    } else if (score === bestScore && score > 0) {
      tie = true
    }
  }

  if (tie) return null

  return bestScore >= 3 ? best : null
}
